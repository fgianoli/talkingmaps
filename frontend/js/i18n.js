    init() {
        const saved = localStorage.getItem('tm_lang');
        this._lang = saved || navigator.language?.substring(0, 2) || 'it';
        if (!['it', 'en', 'es'].includes(this._lang)) this._lang = 'it';
        this._strings = I18n._translations[this._lang] || I18n._translations.it;
        document.documentElement.lang = this._lang;
    },

    setLang(lang) {
        if (!['it', 'en', 'es'].includes(lang)) return;
        this._lang = lang;
        this._strings = I18n._translations[lang] || I18n._translations.it;
        localStorage.setItem('tm_lang', lang);
        document.documentElement.lang = lang;
    },

